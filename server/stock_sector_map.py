def _norm_code(s: str) -> str:
    """把各种写法的 ticker 归一成查表键。

    去交易所后缀(.SS/.SZ/.HK/.SH/.BJ)与前缀(SH/SZ/HK/BJ)，保留纯代码。
    600519 / SH600519 / 600519.SS → "600519"；00700 / 00700.HK → "00700"。
    """
    s = (s or "").strip().upper()
    s = re.sub(r"\.(SS|SZ|SH|HK|BJ)$", "", s)
    s = re.sub(r"^(SH|SZ|HK|BJ)", "", s)
    return s


# 构建查表（模块加载时一次）
_BY_TICKER: Dict[str, str] = {}
_BY_NAME: Dict[str, str] = {}
for _t, _n, _s in _SEED:
    if _t:
        _BY_TICKER[_norm_code(_t)] = _s
    if _n:
        _BY_NAME[_n.strip().lower()] = _s


def lookup(ticker: Optional[str] = None, name: Optional[str] = None) -> Optional[str]:
    """ticker 或 公司名 → 板块；查不到返回 None（调用方回落关键词）。"""
    if ticker:
        sec = _BY_TICKER.get(_norm_code(ticker))
        if sec:
            return sec
    if name:
        sec = _BY_NAME.get((name or "").strip().lower())
        if sec:
            return sec
    return None


def sectors_for_stocks(stocks: Optional[List[Any]]) -> List[str]:
    """一串 ticker/名称（或 {ticker/code/name} 字典）→ 去重板块列表（保序）。

    兼容两种上游形态：Finlight 归一化后是纯字符串列表；newsfeed 等可能直接给
    {"code":..,"name":..} 字典。统一归一后再反查。全查不到返回 []。
    """
    out: List[str] = []
    for tok in (stocks or []):
        if not tok:
            continue
        t: Optional[str] = None
        n: Optional[str] = None
        if isinstance(tok, dict):
            t = tok.get("ticker") or tok.get("code") or tok.get("symbol")
            n = tok.get("name")
            if not isinstance(t, str):
                t = None
            if not isinstance(n, str):
                n = None
        elif isinstance(tok, str):
            t = tok
            n = tok
        else:
            continue
        sec = lookup(ticker=t, name=n)
        if sec and sec not in out:
            out.append(sec)
    return out


def selfcheck() -> int:
    """离线自检（不碰网络/不碰文件）。返回失败条数。"""
    steps = [
        ("茅台 600519→消费", lookup(ticker="600519") == "消费"),
        ("SH600519 去前缀→消费", lookup(ticker="SH600519") == "消费"),
        ("600519.SS 去后缀→消费", lookup(ticker="600519.SS") == "消费"),
        ("宁德时代 300750→新能源", lookup(ticker="300750") == "新能源"),
        ("寒武纪→科技AI", lookup(ticker="688256") == "科技AI"),
        ("Tencent 名称→中概港股", lookup(name="Tencent") == "中概港股"),
        ("腾讯控股 名称→中概港股", lookup(name="腾讯控股") == "中概港股"),
        ("BABA 名称→中概港股", lookup(name="BABA") == "中概港股"),
        ("未知 ticker→None", lookup(ticker="999999") is None),
        ("未知名称→None", lookup(name="NoSuchCo") is None),
        ("多 stocks 反查去重",
         sectors_for_stocks(["600519", "贵州茅台", "Tencent"]) == ["消费", "中概港股"]),
        ("空 stocks→[]", sectors_for_stocks([]) == []),
        ("未知 stocks→[]", sectors_for_stocks(["AAPL", "unknown"]) == []),
        ("字典形态 stocks 反查", sectors_for_stocks(
            [{"ticker": "600519"}, {"name": "Tencent", "code": "00700"}])
         == ["消费", "中概港股"]),
    ]
    fails = 0
    for label, ok in steps:
        print(f"  {'✅' if ok else '❌'} stock_sector_map: {label}")
        if not ok:
            fails += 1
    return fails


