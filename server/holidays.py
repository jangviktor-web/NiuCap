# server/holidays.py
"""A 股本地节假日表（休市日 + 调休补班交易日）。

为什么需要它：
    原 market_state() 只看星期几判周末，**完全不查交易日历**。于是工作日里的
    法定节假日（国庆、春节连休中的工作日等）会被误判成「交易中」，虚拟盘就能
    按上一交易日的静态收盘价成交——这是 #103 收盘后交易 bug 的延伸。
    本表把「非周末的法定休市日」显式列出来，并单独标记「周末中的调休补班日」，
    让 market_state() 能正确判休市。

数据来源与口径：
    * 2026 年：国务院办公厅《关于2026年部分节假日安排的通知》（国办发明电〔2025〕7号），
      已正式发布，准确。
    * 2027 年：国务院办公厅通常于前一年 11 月前后发布，**当前(2026-09)尚未正式公布**，
      下表为依据公开整理（publicholidays.cn 等）的「预测值」，正式公告发布后请以官方为准，
      并同步更新本文件。预测偏差只会「偏严」（多休市），不会造成误交易，安全。

约定（与 market_state 配合）：
    * HOLIDAYS  只列「非周末的法定休市日」。周末由 market_state 的星期判断覆盖，
      无需重复列出（重复也无妨，但保持最小集更易核对）。
    * MAKEUP_WORKDAYS 是「周末中的调休补班日」，本应休市但要开市。漏列只会「偏严」
      多休市一天，不会造成误交易，故 2027 补班日暂留空，待官方补班表公布后补充。
"""

