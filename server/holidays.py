# ---------------------------------------------------------------------------
# 对外聚合
# ---------------------------------------------------------------------------
HOLIDAYS = HOLIDAYS_2026 | HOLIDAYS_2027
MAKEUP_WORKDAYS = MAKEUP_WORKDAYS_2026 | MAKEUP_WORKDAYS_2027


def is_market_holiday(ymd: str) -> bool:
    """ymd 形如 'YYYY-MM-DD'，返回当天是否 A 股休市（法定节假日）。"""
    return ymd in HOLIDAYS


def is_makeup_trading_day(ymd: str) -> bool:
    """ymd 形如 'YYYY-MM-DD'，返回当天是否周末中的调休补班交易日。"""
    return ymd in MAKEUP_WORKDAYS
